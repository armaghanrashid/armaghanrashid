"""README.md composition."""

from __future__ import annotations

import html
from datetime import datetime
from pathlib import Path
from typing import Any

from .cards import card_filename
from .terminal import plain_summary


def _picture(base: str, alt: str, width: str = "100%") -> str:
    return (
        "<picture>"
        f'<source media="(prefers-color-scheme: dark)" srcset="{base}-dark.svg">'
        f'<img alt="{html.escape(alt, quote=True)}" src="{base}-light.svg" width="{width}">'
        "</picture>"
    )


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def existing_media(profile: dict[str, Any], root: Path) -> list[dict[str, Any]]:
    return [m for m in profile["media"] if (root / "assets" / "media" / m["file"]).is_file()]


def media_section(profile: dict[str, Any], root: Path) -> str:
    items = existing_media(profile, root)
    if not items:
        return ""
    login = profile["login"]
    cells = []
    for m in items:
        link = f"https://github.com/{login}/{m['repo']}"
        alt = html.escape(f"{m['repo']}: {m['caption']}", quote=True)
        cells.append(
            f'<td width="33%" valign="top"><a href="{link}">'
            f'<img src="assets/media/{m["file"]}" alt="{alt}" width="100%"></a><br>'
            f"<sub><b>{html.escape(m['repo'])}</b> · {html.escape(m['caption'])}</sub></td>"
        )
    # Three across; two or four items read better as a 2-wide grid than with empty cells.
    cols = 2 if len(cells) in (2, 4) else 3
    width = "50%" if cols == 2 else "33%"
    cells = [c.replace('<td width="33%"', f'<td width="{width}"', 1) for c in cells]
    rows = []
    for i in range(0, len(cells), cols):
        chunk = cells[i:i + cols] + [f'<td width="{width}"></td>'] * (cols - len(cells[i:i + cols]))
        rows.append("<tr>\n" + "\n".join(chunk) + "\n</tr>")
    return "### See it run\n\n<table>\n" + "\n".join(rows) + "\n</table>\n\n"


def cards_section(profile: dict[str, Any]) -> str:
    login = profile["login"]
    cells = []
    for p in profile["projects"]:
        base = "assets/" + card_filename(p["repo"], "dark")[: -len("-dark.svg")]
        alt = f"{p['repo']}: {p['desc']}"
        cells.append(
            f'<td width="50%" valign="top"><a href="https://github.com/{login}/{p["repo"]}">'
            f"{_picture(base, alt)}</a></td>"
        )
    rows = [
        "<tr>\n" + "\n".join(cells[i:i + 2]) + "\n</tr>" for i in range(0, len(cells), 2)
    ]
    return "### Featured builds\n\n<table>\n" + "\n".join(rows) + "\n</table>\n\n"


def experience_table(profile: dict[str, Any]) -> str:
    rows = ["| Role | Where | Impact |", "| --- | --- | --- |"]
    for e in profile["experience"]:
        role = f"{_cell(e['role'])}<br><sub>{_cell(e['year'])}</sub>"
        impact = e["impact"].replace("|", "\\|")
        rows.append(f"| {role} | {_cell(e['org_full'])} | {impact} |")
    return "\n".join(rows)


def stack_table(profile: dict[str, Any]) -> str:
    rows = [
        f"<tr><td><b>{html.escape(name)}</b></td>"
        f"<td>{html.escape(' · '.join(items))}</td></tr>"
        for name, items in profile["stack"].items()
    ]
    return "<table>\n" + "\n".join(rows) + "\n</table>"


def build_readme(
    profile: dict[str, Any], statuses: dict[str, str], now: datetime, root: Path
) -> str:
    alt = plain_summary(profile, statuses, now)
    closed = " · ".join(f"{c['name']} ({c['desc']})" for c in profile["closed_source"])
    parts = [
        "<!-- Generated by profile-gen from profile.yaml. Do not edit by hand. -->\n\n",
        f'<p align="center">{_picture("assets/terminal", alt)}</p>\n\n',
        media_section(profile, root),
        f"### In plain text\n\n{profile['summary']}\n\n",
        cards_section(profile),
        f"**Closed source, in development:** {closed}\n\n",
        f"### Experience\n\n{experience_table(profile)}\n\n",
        f"### Stack\n\n{stack_table(profile)}\n\n",
        "<sub>This page is generated by profile-gen from profile.yaml and rebuilt nightly by "
        f'GitHub Actions. · <a href="{profile["linkedin"]}">LinkedIn</a></sub>\n',
    ]
    return "".join(parts)
