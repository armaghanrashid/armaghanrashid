from __future__ import annotations

import re
import shutil
from datetime import UTC, datetime
from pathlib import Path

from profile_gen.build import generate

from .conftest import NOW, ROOT


def local_refs(readme: str) -> set[str]:
    refs = re.findall(r'(?:src|srcset|href)="([^"]+)"', readme)
    refs += re.findall(r"\]\(([^)]+)\)", readme)
    return {r for r in refs if not re.match(r"[a-z]+:|#", r)}


def test_readme_links_no_missing_local_files(built):
    readme = (built / "README.md").read_text()
    refs = local_refs(readme)
    assert refs, "expected local asset references"
    for ref in refs:
        assert (built / ref).is_file(), ref


def test_see_it_run_omitted_when_no_media_exists(built):
    readme = (built / "README.md").read_text()
    assert "See it run" not in readme and "assets/media" not in readme


def test_see_it_run_only_lists_existing_files(tmp_path, statuses):
    shutil.copy(ROOT / "profile.yaml", tmp_path / "profile.yaml")
    media = tmp_path / "assets" / "media"
    media.mkdir(parents=True)
    (media / "parallax.gif").write_bytes(b"GIF89a")
    generate(tmp_path, now=NOW, statuses=statuses)
    readme = (tmp_path / "README.md").read_text()
    assert "### See it run" in readme
    assert "assets/media/parallax.gif" in readme
    assert "enclave.png" not in readme and "meridian.png" not in readme
    assert 'href="https://github.com/armaghanrashid/parallax-ball-tracker"' in readme
    for ref in local_refs(readme):
        assert (tmp_path / ref).is_file(), ref


def test_section_order(built):
    r = (built / "README.md").read_text()
    order = ["<picture>", "### In plain text", "### Featured builds", "**Closed source, in development:**",
             "### Experience", "### Stack", "This page is generated by profile-gen"]
    pos = [r.index(m) for m in order]
    assert pos == sorted(pos)


def test_readme_content(built, profile):
    r = (built / "README.md").read_text()
    assert 'media="(prefers-color-scheme: dark)"' in r
    assert "assets/terminal-dark.svg" in r and "assets/terminal-light.svg" in r
    assert profile["summary"] in r
    for p in profile["projects"]:
        assert f'href="https://github.com/armaghanrashid/{p["repo"]}"' in r
        assert f"assets/card-{p['repo']}-dark.svg" in r and f"assets/card-{p['repo']}-light.svg" in r
    assert "| Role | Where | Impact |" in r
    assert "**40% lower latency**" in r
    assert "Slate (offline-first personal finance app) · Orca (on-device lecture transcription for macOS)" in r
    assert "rebuilt nightly by GitHub Actions." in r
    assert profile["linkedin"] in r


def test_alt_text_is_a_full_summary(built):
    r = (built / "README.md").read_text()
    alt = re.search(r'<img alt="([^"]+)" src="assets/terminal-light.svg"', r).group(1)
    for needle in ("Muhammad Armaghan Rashid", "McGill", "Visionet", "enclave-messenger", "2027"):
        assert needle in alt


def test_no_private_paths_or_emoji(built):
    for f in [built / "README.md", *(built / "assets").glob("*.svg")]:
        s = f.read_text()
        assert "/Users/" not in s
        assert not re.search("[\U0001F300-\U0001FAFF☀-⛿]", s), f.name


def test_generation_is_deterministic(tmp_path, statuses):
    shutil.copy(ROOT / "profile.yaml", tmp_path / "profile.yaml")
    generate(tmp_path, now=NOW, statuses=statuses)
    first = {p.name: p.read_bytes() for p in Path(tmp_path).rglob("*") if p.is_file()}
    generate(tmp_path, now=datetime(2026, 10, 9, 7, 12, tzinfo=UTC), statuses=statuses)
    second = {p.name: p.read_bytes() for p in Path(tmp_path).rglob("*") if p.is_file()}
    assert first == second
